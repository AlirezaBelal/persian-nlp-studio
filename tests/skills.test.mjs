import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, writeFileSync, statSync, existsSync, readdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { setup, manifest, pin } from '../scripts/setup-codex-skills.mjs';
const root = fileURLToPath(new URL('../', import.meta.url));
test('malformed metadata and unsupported arguments fail before writes', () => {
  assert.throws(() => manifest('name: missing delimiters', 'bad'), /frontmatter/);
  assert.throws(() => manifest('---\nname: x\n---\n', 'bad'), /frontmatter/);
  assert.throws(() => setup(root, '--global'), /Usage/);
  assert.throws(() => setup(root, '--check', 'nonexistent-git-prerequisite'), /ENOENT/);
});
test('real clean checkout, installation, repetition and corruption rejection', { skip: !existsSync(join(root, 'vendor/codex-skills/.git')) }, () => {
  const target = mkdtempSync(join(tmpdir(), 'persian-skills-test-'));
  const git = args => execFileSync('git', args, { encoding:'utf8', stdio:['ignore','pipe','pipe'] });
  git(['clone', '--no-hardlinks', '--no-recurse-submodules', root, target]);
  assert.throws(() => setup(target), /Submodule missing/);
  git(['clone', '--no-hardlinks', join(root, 'vendor/codex-skills'), join(target, 'vendor/codex-skills')]);
  git(['-C', join(target, 'vendor/codex-skills'), 'checkout', pin]);
  assert.throws(() => setup(target, '--check'), /missing or modified/);
  git(['-C', join(target, 'vendor/codex-skills'), 'checkout', pin+'^']);
  assert.throws(() => setup(target), /Unexpected upstream SHA/);
  git(['-C', join(target, 'vendor/codex-skills'), 'checkout', pin]);
  setup(target);
  const file = join(target, '.agents/skills/planner/SKILL.md');
  const time = statSync(file).mtimeMs;
  setup(target); setup(target, '--check');
  assert.equal(statSync(file).mtimeMs, time);
  assert.deepEqual(readdirSync(join(target, '.agents/skills')).sort(), ['frontend-responsive-ui','planner']);
  writeFileSync(file, 'broken');
  assert.throws(() => setup(target, '--check'), /missing or modified/);
  setup(target); setup(target, '--check');
  const upstream = join(target, 'vendor/codex-skills/skills/planner/SKILL.md');
  writeFileSync(upstream, readFileSync(upstream, 'utf8') + '\nchanged');
  assert.throws(() => setup(target), /dirty/);
});
